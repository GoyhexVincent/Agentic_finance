-- 6.1 Toutes les paires : corrélation de Pearson, n_obs, IC 95 % de Fisher.
CREATE OR REPLACE FUNCTION finance.corr_pairs(
    p_start   DATE DEFAULT DATE '2015-01-01',
    p_end     DATE DEFAULT CURRENT_DATE,
    p_basis   TEXT DEFAULT 'EUR',
    p_min_obs INTEGER DEFAULT 60
)
RETURNS TABLE (
    asset_a      TEXT,
    asset_b      TEXT,
    correlation  NUMERIC,
    n_obs        BIGINT,
    ci_low       NUMERIC,
    ci_high      NUMERIC,
    first_date   DATE,
    last_date    DATE,
    a_order      SMALLINT,
    b_order      SMALLINT
)
LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
BEGIN
    IF UPPER(p_basis) NOT IN ('EUR', 'LOCAL') THEN
        RAISE EXCEPTION 'p_basis doit être EUR ou LOCAL (reçu %)', p_basis;
    END IF;
    IF p_min_obs < 3 THEN
        RAISE EXCEPTION 'p_min_obs doit être >= 3 (reçu %)', p_min_obs;
    END IF;

    RETURN QUERY
    WITH r AS (
        SELECT v.asset_id,
               v.trade_date,
               CASE WHEN UPPER(p_basis) = 'LOCAL' THEN v.ret_local ELSE v.ret_eur END AS ret
        FROM finance.v_returns v
        WHERE v.trade_date BETWEEN p_start AND p_end
    ), pairs AS (
        SELECT a.asset_id AS aid,
               b.asset_id AS bid,
               corr(a.ret, b.ret) AS r,
               COUNT(*) AS n,
               MIN(a.trade_date) AS d0,
               MAX(a.trade_date) AS d1
        FROM r a
        JOIN r b
          ON b.trade_date = a.trade_date
         AND b.asset_id > a.asset_id
        WHERE a.ret IS NOT NULL
          AND b.ret IS NOT NULL
        GROUP BY a.asset_id, b.asset_id
        HAVING COUNT(*) >= p_min_obs
    )
    SELECT aa.ticker,
           bb.ticker,
           p.r::numeric(10, 4),
           p.n,
           CASE WHEN p.n > 3
                THEN TANH(ATANH(p.r) - 1.96 / SQRT(p.n - 3))::numeric(10, 4)
           END,
           CASE WHEN p.n > 3
                THEN TANH(ATANH(p.r) + 1.96 / SQRT(p.n - 3))::numeric(10, 4)
           END,
           p.d0,
           p.d1,
           aa.display_order,
           bb.display_order
    FROM pairs p
    JOIN finance.assets aa ON aa.asset_id = p.aid
    JOIN finance.assets bb ON bb.asset_id = p.bid
    ORDER BY aa.display_order, bb.display_order;
END;
$$;

COMMENT ON FUNCTION finance.corr_pairs(DATE, DATE, TEXT, INTEGER) IS
    'Corrélations par paires avec nombre d''observations et intervalle de confiance de Fisher.';

-- 6.2 Corrélations avec un benchmark (URTH par défaut).
CREATE OR REPLACE FUNCTION finance.corr_benchmark(
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR',
    p_benchmark TEXT DEFAULT 'URTH',
    p_min_obs   INTEGER DEFAULT 60
)
RETURNS TABLE (
    asset        TEXT,
    benchmark    TEXT,
    correlation  NUMERIC,
    n_obs        BIGINT,
    ci_low       NUMERIC,
    ci_high      NUMERIC,
    first_date   DATE,
    last_date    DATE,
    display_order SMALLINT
)
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN cp.asset_a = p_benchmark THEN cp.asset_b ELSE cp.asset_a END,
           p_benchmark,
           cp.correlation,
           cp.n_obs,
           cp.ci_low,
           cp.ci_high,
           cp.first_date,
           cp.last_date,
           CASE WHEN cp.asset_a = p_benchmark THEN cp.b_order ELSE cp.a_order END
    FROM finance.corr_pairs(p_start, p_end, p_basis, p_min_obs) cp
    WHERE cp.asset_a = p_benchmark OR cp.asset_b = p_benchmark
    ORDER BY ABS(cp.correlation) DESC;
$$;

COMMENT ON FUNCTION finance.corr_benchmark(DATE, DATE, TEXT, TEXT, INTEGER) IS
    'Corrélations de chaque actif avec le benchmark, triées par force décroissante.';

-- 6.3 Corrélations annuelles avec le benchmark.
CREATE OR REPLACE FUNCTION finance.corr_by_year(
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR',
    p_benchmark TEXT DEFAULT 'URTH',
    p_min_obs   INTEGER DEFAULT 20
)
RETURNS TABLE (
    year         INTEGER,
    asset        TEXT,
    correlation  NUMERIC,
    n_obs        BIGINT,
    display_order SMALLINT
)
LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE
    v_bench SMALLINT;
    v_col   TEXT;
BEGIN
    IF UPPER(p_basis) NOT IN ('EUR', 'LOCAL') THEN
        RAISE EXCEPTION 'p_basis doit être EUR ou LOCAL (reçu %)', p_basis;
    END IF;

    SELECT asset_id INTO v_bench FROM finance.assets WHERE ticker = p_benchmark;
    IF v_bench IS NULL THEN
        RAISE EXCEPTION 'Benchmark inconnu : %', p_benchmark;
    END IF;
    v_col := CASE WHEN UPPER(p_basis) = 'LOCAL' THEN 'ret_local' ELSE 'ret_eur' END;

    RETURN QUERY EXECUTE format($q$
        WITH r AS (
            SELECT asset_id, trade_date, %1$I AS ret
            FROM finance.v_returns
            WHERE trade_date BETWEEN $1 AND $2
        ), b AS (
            SELECT trade_date, ret FROM r WHERE asset_id = $3
        ), pairs AS (
            SELECT a.asset_id,
                   EXTRACT(YEAR FROM a.trade_date)::int AS yr,
                   corr(a.ret, b.ret) AS c,
                   count(*) AS n
            FROM r a
            JOIN b ON b.trade_date = a.trade_date
            WHERE a.asset_id <> $3
              AND a.ret IS NOT NULL
              AND b.ret IS NOT NULL
            GROUP BY a.asset_id, EXTRACT(YEAR FROM a.trade_date)
            HAVING count(*) >= $4
        )
        SELECT p.yr, aa.ticker, p.c::numeric(10,4), p.n, aa.display_order
        FROM pairs p
        JOIN finance.assets aa USING (asset_id)
        ORDER BY p.yr, aa.display_order
    $q$, v_col) USING p_start, p_end, v_bench, p_min_obs;
END;
$$;

COMMENT ON FUNCTION finance.corr_by_year(DATE, DATE, TEXT, TEXT, INTEGER) IS
    'Corrélations annualisées avec le benchmark, pour visualiser les régimes.';

-- 6.4 Corrélation glissante d'un actif contre un benchmark.
CREATE OR REPLACE FUNCTION finance.rolling_corr(
    p_asset     TEXT,
    p_benchmark TEXT DEFAULT 'URTH',
    p_window    INTEGER DEFAULT 126,
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR'
)
RETURNS TABLE (
    trade_date  DATE,
    correlation NUMERIC,
    n_obs       BIGINT
)
LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE
    v_a   SMALLINT;
    v_b   SMALLINT;
    v_col TEXT;
BEGIN
    IF UPPER(p_basis) NOT IN ('EUR', 'LOCAL') THEN
        RAISE EXCEPTION 'p_basis doit être EUR ou LOCAL (reçu %)', p_basis;
    END IF;
    IF p_window < 10 THEN
        RAISE EXCEPTION 'p_window doit être >= 10 (reçu %)', p_window;
    END IF;

    SELECT asset_id INTO v_a FROM finance.assets WHERE ticker = p_asset;
    IF v_a IS NULL THEN
        RAISE EXCEPTION 'Actif inconnu : %', p_asset;
    END IF;
    SELECT asset_id INTO v_b FROM finance.assets WHERE ticker = p_benchmark;
    IF v_b IS NULL THEN
        RAISE EXCEPTION 'Benchmark inconnu : %', p_benchmark;
    END IF;

    v_col := CASE WHEN UPPER(p_basis) = 'LOCAL' THEN 'ret_local' ELSE 'ret_eur' END;

    RETURN QUERY EXECUTE format($q$
        WITH paired AS (
            SELECT a.trade_date, a.%1$I AS ra, b.%1$I AS rb
            FROM finance.v_returns a
            JOIN finance.v_returns b
              ON b.trade_date = a.trade_date
             AND b.asset_id = $2
            WHERE a.asset_id = $1
              AND a.trade_date BETWEEN $3 AND $4
              AND a.%1$I IS NOT NULL
              AND b.%1$I IS NOT NULL
        ), calc AS (
            SELECT trade_date,
                   corr(ra, rb) OVER (
                       ORDER BY trade_date
                       ROWS BETWEEN %2$s PRECEDING AND CURRENT ROW
                   ) AS c,
                   count(*) OVER (
                       ORDER BY trade_date
                       ROWS BETWEEN %2$s PRECEDING AND CURRENT ROW
                   ) AS n
            FROM paired
        )
        SELECT trade_date, c::numeric(10,4), n
        FROM calc
        WHERE c IS NOT NULL
        ORDER BY trade_date
    $q$, v_col, p_window - 1)
    USING v_a, v_b, p_start, p_end;
END;
$$;

COMMENT ON FUNCTION finance.rolling_corr(TEXT, TEXT, INTEGER, DATE, DATE, TEXT) IS
    'Corrélation glissante sur les N dernières observations communes avec le benchmark.';

-- 6.5 Corrélation glissante de tous les actifs contre un benchmark.
CREATE OR REPLACE FUNCTION finance.rolling_corr_all(
    p_benchmark TEXT DEFAULT 'URTH',
    p_window    INTEGER DEFAULT 126,
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR'
)
RETURNS TABLE (
    asset        TEXT,
    trade_date   DATE,
    correlation  NUMERIC,
    n_obs        BIGINT,
    display_order SMALLINT
)
LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE
    v_b   SMALLINT;
    v_col TEXT;
BEGIN
    IF UPPER(p_basis) NOT IN ('EUR', 'LOCAL') THEN
        RAISE EXCEPTION 'p_basis doit être EUR ou LOCAL (reçu %)', p_basis;
    END IF;
    IF p_window < 10 THEN
        RAISE EXCEPTION 'p_window doit être >= 10 (reçu %)', p_window;
    END IF;

    SELECT asset_id INTO v_b FROM finance.assets WHERE ticker = p_benchmark;
    IF v_b IS NULL THEN
        RAISE EXCEPTION 'Benchmark inconnu : %', p_benchmark;
    END IF;
    v_col := CASE WHEN UPPER(p_basis) = 'LOCAL' THEN 'ret_local' ELSE 'ret_eur' END;

    RETURN QUERY EXECUTE format($q$
        WITH paired AS (
            SELECT a.asset_id, a.trade_date, a.%1$I AS ra, b.%1$I AS rb
            FROM finance.v_returns a
            JOIN finance.v_returns b
              ON b.trade_date = a.trade_date
             AND b.asset_id = $1
            WHERE a.asset_id <> $1
              AND a.trade_date BETWEEN $2 AND $3
              AND a.%1$I IS NOT NULL
              AND b.%1$I IS NOT NULL
        ), calc AS (
            SELECT asset_id,
                   trade_date,
                   corr(ra, rb) OVER (
                       PARTITION BY asset_id
                       ORDER BY trade_date
                       ROWS BETWEEN %2$s PRECEDING AND CURRENT ROW
                   ) AS c,
                   count(*) OVER (
                       PARTITION BY asset_id
                       ORDER BY trade_date
                       ROWS BETWEEN %2$s PRECEDING AND CURRENT ROW
                   ) AS n
            FROM paired
        )
        SELECT aa.ticker, c.trade_date, c.c::numeric(10,4), c.n, aa.display_order
        FROM calc c
        JOIN finance.assets aa USING (asset_id)
        WHERE c.c IS NOT NULL
        ORDER BY aa.display_order, c.trade_date
    $q$, v_col, p_window - 1)
    USING v_b, p_start, p_end;
END;
$$;

COMMENT ON FUNCTION finance.rolling_corr_all(TEXT, INTEGER, DATE, DATE, TEXT) IS
    'Série de corrélations glissantes de tous les actifs contre le benchmark.';

-- 6.6 Snapshot mensuel : dernière corrélation glissante de chaque mois.
CREATE OR REPLACE FUNCTION finance.corr_monthly(
    p_benchmark TEXT DEFAULT 'URTH',
    p_window    INTEGER DEFAULT 126,
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR'
)
RETURNS TABLE (
    month        DATE,
    asset        TEXT,
    correlation  NUMERIC,
    n_obs        BIGINT,
    display_order SMALLINT
)
LANGUAGE sql STABLE AS $$
    SELECT DISTINCT ON (date_trunc('month', r.trade_date)::date, r.display_order)
           date_trunc('month', r.trade_date)::date AS month,
           r.asset,
           r.correlation,
           r.n_obs,
           r.display_order
    FROM finance.rolling_corr_all(p_benchmark, p_window, p_start, p_end, p_basis) r
    ORDER BY date_trunc('month', r.trade_date)::date, r.display_order, r.trade_date DESC;
$$;

COMMENT ON FUNCTION finance.corr_monthly(TEXT, INTEGER, DATE, DATE, TEXT) IS
    'Dernière corrélation glissante de chaque mois, pour les snapshots temporels.';

-- 6.7 Bêta et R² d'un actif contre un benchmark.
CREATE OR REPLACE FUNCTION finance.beta_vs_benchmark(
    p_asset     TEXT,
    p_benchmark TEXT DEFAULT 'URTH',
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR'
)
RETURNS TABLE (
    asset        TEXT,
    benchmark    TEXT,
    beta         NUMERIC,
    r2           NUMERIC,
    correlation  NUMERIC,
    n_obs        BIGINT
)
LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE
    v_a   SMALLINT;
    v_b   SMALLINT;
    v_col TEXT;
BEGIN
    IF UPPER(p_basis) NOT IN ('EUR', 'LOCAL') THEN
        RAISE EXCEPTION 'p_basis doit être EUR ou LOCAL (reçu %)', p_basis;
    END IF;

    SELECT asset_id INTO v_a FROM finance.assets WHERE ticker = p_asset;
    IF v_a IS NULL THEN
        RAISE EXCEPTION 'Actif inconnu : %', p_asset;
    END IF;
    SELECT asset_id INTO v_b FROM finance.assets WHERE ticker = p_benchmark;
    IF v_b IS NULL THEN
        RAISE EXCEPTION 'Benchmark inconnu : %', p_benchmark;
    END IF;

    v_col := CASE WHEN UPPER(p_basis) = 'LOCAL' THEN 'ret_local' ELSE 'ret_eur' END;

    RETURN QUERY EXECUTE format($q$
        WITH r AS (
            SELECT asset_id, trade_date, %1$I AS ret
            FROM finance.v_returns
            WHERE trade_date BETWEEN $1 AND $2
        ), joined AS (
            SELECT a.ret AS ra, b.ret AS rb
            FROM r a
            JOIN r b ON b.trade_date = a.trade_date
            WHERE a.asset_id = $3
              AND b.asset_id = $4
              AND a.ret IS NOT NULL
              AND b.ret IS NOT NULL
        )
        SELECT $5::text, $6::text,
               regr_slope(ra, rb)::numeric(10,4),
               regr_r2(ra, rb)::numeric(10,4),
               corr(ra, rb)::numeric(10,4),
               count(*)
        FROM joined
        HAVING count(*) >= 3
    $q$, v_col)
    USING p_start, p_end, v_a, v_b, p_asset, p_benchmark;
END;
$$;

COMMENT ON FUNCTION finance.beta_vs_benchmark(TEXT, TEXT, DATE, DATE, TEXT) IS
    'Bêta (pente), R² et corrélation d''un actif contre un benchmark.';

-- 6.8 Corrélation conditionnelle en stress : jours où le benchmark baisse.
CREATE OR REPLACE FUNCTION finance.stress_corr(
    p_benchmark TEXT DEFAULT 'URTH',
    p_threshold NUMERIC DEFAULT -0.01,
    p_start     DATE DEFAULT DATE '2015-01-01',
    p_end       DATE DEFAULT CURRENT_DATE,
    p_basis     TEXT DEFAULT 'EUR',
    p_min_obs   INTEGER DEFAULT 20
)
RETURNS TABLE (
    asset                 TEXT,
    correlation_stress    NUMERIC,
    n_stress              BIGINT,
    correlation_all       NUMERIC,
    n_all                 BIGINT,
    display_order         SMALLINT
)
LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE
    v_b   SMALLINT;
    v_col TEXT;
BEGIN
    IF UPPER(p_basis) NOT IN ('EUR', 'LOCAL') THEN
        RAISE EXCEPTION 'p_basis doit être EUR ou LOCAL (reçu %)', p_basis;
    END IF;
    IF p_threshold >= 0 THEN
        RAISE EXCEPTION 'p_threshold doit être négatif (ex. -0.01 pour -1 %%)';
    END IF;

    SELECT asset_id INTO v_b FROM finance.assets WHERE ticker = p_benchmark;
    IF v_b IS NULL THEN
        RAISE EXCEPTION 'Benchmark inconnu : %', p_benchmark;
    END IF;
    v_col := CASE WHEN UPPER(p_basis) = 'LOCAL' THEN 'ret_local' ELSE 'ret_eur' END;

    RETURN QUERY EXECUTE format($q$
        WITH r AS (
            SELECT asset_id, trade_date, %1$I AS ret
            FROM finance.v_returns
            WHERE trade_date BETWEEN $1 AND $2
        ), b AS (
            SELECT trade_date, ret FROM r WHERE asset_id = $3
        ), joined AS (
            SELECT a.asset_id, a.ret AS ra, b.ret AS rb
            FROM r a
            JOIN b ON b.trade_date = a.trade_date
            WHERE a.asset_id <> $3
              AND a.ret IS NOT NULL
              AND b.ret IS NOT NULL
        ), agg AS (
            SELECT asset_id,
                   corr(ra, rb) FILTER (WHERE rb < $4) AS cs,
                   count(*) FILTER (WHERE rb < $4) AS ns,
                   corr(ra, rb) AS ca,
                   count(*) AS na
            FROM joined
            GROUP BY asset_id
        )
        SELECT aa.ticker, a.cs::numeric(10,4), a.ns, a.ca::numeric(10,4), a.na, aa.display_order
        FROM agg a
        JOIN finance.assets aa USING (asset_id)
        WHERE a.ns >= $5
        ORDER BY a.cs DESC NULLS LAST
    $q$, v_col)
    USING p_start, p_end, v_b, p_threshold, p_min_obs;
END;
$$;

COMMENT ON FUNCTION finance.stress_corr(TEXT, NUMERIC, DATE, DATE, TEXT, INTEGER) IS
    'Corrélation les jours de baisse du benchmark (stress) vs corrélation sur toute la période.';

-- 6.9 Matrices larges pour Grafana.
--  Grafana ne sait pas pivoter nativement une matrice catégorielle. Ces trois
--  fonctions renvoient une ligne par actif et une colonne par comparateur.
--  La liste est volontairement figée : ajouter un actif au univers "core"
--  nécessite d'ajouter la colonne correspondante ici (ou de régénérer le SQL).
CREATE OR REPLACE FUNCTION finance.corr_matrix_core(
    p_start   DATE DEFAULT DATE '2015-01-01',
    p_end     DATE DEFAULT CURRENT_DATE,
    p_basis   TEXT DEFAULT 'EUR',
    p_min_obs INTEGER DEFAULT 60
)
RETURNS TABLE (
    asset TEXT,
    "XLK" NUMERIC, "XLV" NUMERIC, "XLF" NUMERIC, "XLY" NUMERIC, "XLC" NUMERIC,
    "XLI" NUMERIC, "XLP" NUMERIC, "XLE" NUMERIC, "XLU" NUMERIC, "XLRE" NUMERIC,
    "XLB" NUMERIC, "URTH" NUMERIC, "BTC" NUMERIC, "GLD" NUMERIC, "TLT" NUMERIC
)
LANGUAGE sql STABLE AS $$
    WITH p AS (
        SELECT * FROM finance.corr_pairs(p_start, p_end, p_basis, p_min_obs)
    ), long AS (
        SELECT asset_a AS asset, asset_b AS other, correlation FROM p
        UNION ALL
        SELECT asset_b, asset_a, correlation FROM p
        UNION ALL
        SELECT ticker, ticker, 1.0::numeric FROM finance.assets WHERE universe = 'core'
    )
    SELECT a.ticker,
           MAX(CASE WHEN l.other = 'XLK'  THEN l.correlation END)::numeric(10,4) AS "XLK",
           MAX(CASE WHEN l.other = 'XLV'  THEN l.correlation END)::numeric(10,4) AS "XLV",
           MAX(CASE WHEN l.other = 'XLF'  THEN l.correlation END)::numeric(10,4) AS "XLF",
           MAX(CASE WHEN l.other = 'XLY'  THEN l.correlation END)::numeric(10,4) AS "XLY",
           MAX(CASE WHEN l.other = 'XLC'  THEN l.correlation END)::numeric(10,4) AS "XLC",
           MAX(CASE WHEN l.other = 'XLI'  THEN l.correlation END)::numeric(10,4) AS "XLI",
           MAX(CASE WHEN l.other = 'XLP'  THEN l.correlation END)::numeric(10,4) AS "XLP",
           MAX(CASE WHEN l.other = 'XLE'  THEN l.correlation END)::numeric(10,4) AS "XLE",
           MAX(CASE WHEN l.other = 'XLU'  THEN l.correlation END)::numeric(10,4) AS "XLU",
           MAX(CASE WHEN l.other = 'XLRE' THEN l.correlation END)::numeric(10,4) AS "XLRE",
           MAX(CASE WHEN l.other = 'XLB'  THEN l.correlation END)::numeric(10,4) AS "XLB",
           MAX(CASE WHEN l.other = 'URTH' THEN l.correlation END)::numeric(10,4) AS "URTH",
           MAX(CASE WHEN l.other = 'BTC'  THEN l.correlation END)::numeric(10,4) AS "BTC",
           MAX(CASE WHEN l.other = 'GLD'  THEN l.correlation END)::numeric(10,4) AS "GLD",
           MAX(CASE WHEN l.other = 'TLT'  THEN l.correlation END)::numeric(10,4) AS "TLT"
    FROM finance.assets a
    LEFT JOIN long l ON l.asset = a.ticker
    WHERE a.universe = 'core'
    GROUP BY a.ticker, a.display_order, a.asset_id
    ORDER BY a.asset_id;
$$;

COMMENT ON FUNCTION finance.corr_matrix_core(DATE, DATE, TEXT, INTEGER) IS
    'Matrice 15 × 15 des actifs core, une ligne par actif, une colonne par comparateur.';

