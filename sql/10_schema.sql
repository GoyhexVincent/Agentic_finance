-- ───────────────────────────────────────────────────────────────────────────
--  5. Vues de rendements et de statistiques
-- ───────────────────────────────────────────────────────────────────────────
--  Le taux de change est joint « as of » : dernier taux connu à la date de
--  séance. Les jours fériés de FX ne créent donc pas de trou.
--  Pour un actif coté en EUR, le taux vaut 1 ; pour les autres, il est NULL
--  si aucun taux n'est encore disponible (pas de conversion inventée).
CREATE OR REPLACE VIEW finance.v_returns AS
WITH base AS (
    SELECT p.asset_id,
           p.trade_date,
           p.adj_close,
           CASE
               WHEN p.currency = 'EUR' THEN 1.0::numeric
               ELSE fx.eur_per_unit
           END AS eur_per_unit
    FROM finance.prices_daily p
    LEFT JOIN LATERAL (
        SELECT f.eur_per_unit
        FROM finance.fx_daily f
        WHERE f.currency = p.currency
          AND f.trade_date <= p.trade_date
        ORDER BY f.trade_date DESC
        LIMIT 1
    ) fx ON TRUE
), calc AS (
    SELECT asset_id,
           trade_date,
           adj_close,
           adj_close * eur_per_unit AS adj_close_eur,
           LAG(adj_close) OVER (PARTITION BY asset_id ORDER BY trade_date) AS prev_adj_close,
           LAG(adj_close * eur_per_unit) OVER (PARTITION BY asset_id ORDER BY trade_date) AS prev_adj_close_eur
    FROM base
)
SELECT asset_id,
       trade_date,
       adj_close,
       adj_close_eur,
       LN(adj_close / prev_adj_close) AS ret_local,
       LN(adj_close_eur / prev_adj_close_eur) AS ret_eur
FROM calc
WHERE prev_adj_close IS NOT NULL;

COMMENT ON VIEW finance.v_returns IS
    'Rendements logarithmiques locaux et convertis en EUR, calculés sur l''historique propre de chaque actif.';

CREATE OR REPLACE VIEW finance.v_asset_stats AS
WITH r AS (
    SELECT asset_id, trade_date, adj_close_eur, ret_eur
    FROM finance.v_returns
), stats AS (
    SELECT asset_id,
           MIN(trade_date) AS first_date,
           MAX(trade_date) AS last_date,
           COUNT(ret_eur) AS n_obs,
           STDDEV_SAMP(ret_eur) * SQRT(252) AS annualized_vol,
           EXP(SUM(ret_eur)) - 1 AS cumulative_return
    FROM r
    GROUP BY asset_id
), drawdown_raw AS (
    SELECT asset_id,
           adj_close_eur / MAX(adj_close_eur) OVER (
               PARTITION BY asset_id ORDER BY trade_date
           ) - 1 AS dd
    FROM r
    WHERE adj_close_eur IS NOT NULL
), drawdown AS (
    SELECT asset_id, MIN(dd) AS max_drawdown
    FROM drawdown_raw
    GROUP BY asset_id
)
SELECT a.ticker,
       a.name,
       a.asset_type,
       a.category,
       a.universe,
       s.first_date,
       s.last_date,
       s.n_obs,
       ROUND(s.annualized_vol::numeric, 4) AS annualized_vol,
       ROUND(s.cumulative_return, 4) AS cumulative_return,
       ROUND(d.max_drawdown, 4) AS max_drawdown,
       a.cluster_id,
       a.display_order
FROM finance.assets a
JOIN stats s USING (asset_id)
LEFT JOIN drawdown d USING (asset_id)
ORDER BY a.display_order;

COMMENT ON VIEW finance.v_asset_stats IS
    'Volatilité annualisée, rendement cumulé et drawdown maximal, calculés en EUR.';

CREATE OR REPLACE VIEW finance.v_freshness AS
WITH last_run AS (
    SELECT MAX(finished_at) AS finished_at
    FROM finance.ingestion_runs
    WHERE status IN ('success', 'partial')
)
SELECT a.ticker,
       a.name,
       a.universe,
       MAX(p.trade_date) AS last_trade_date,
       (CURRENT_DATE - MAX(p.trade_date)) AS days_since_last_trade,
       MAX(p.ingested_at) AS last_ingested_at,
       lr.finished_at AS last_run_finished_at,
       ROUND(EXTRACT(EPOCH FROM (NOW() - lr.finished_at)) / 3600.0, 1) AS hours_since_last_run,
       a.display_order
FROM finance.assets a
LEFT JOIN finance.prices_daily p USING (asset_id)
CROSS JOIN last_run lr
GROUP BY a.asset_id, a.ticker, a.name, a.universe, a.display_order, lr.finished_at
ORDER BY a.display_order;

COMMENT ON VIEW finance.v_freshness IS
    'Fraîcheur par actif : dernière séance, âge, dernier import réussi.';

