CREATE SCHEMA IF NOT EXISTS finance;
SET search_path TO finance, public;

-- ───────────────────────────────────────────────────────────────────────────
--  1. finance.assets — référentiel des actifs suivis
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS finance.assets (
    asset_id        SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker          TEXT        NOT NULL UNIQUE,
    yahoo_symbol    TEXT        NOT NULL UNIQUE,
    name            TEXT        NOT NULL,
    asset_type      TEXT        NOT NULL CHECK (asset_type IN ('etf', 'equity', 'crypto')),
    category        TEXT        NOT NULL,
    universe        TEXT        NOT NULL DEFAULT 'core'
                                CHECK (universe IN ('core', 'stock', 'tech')),
    currency        CHAR(3)     NOT NULL,
    exchange        TEXT,
    is_benchmark    BOOLEAN     NOT NULL DEFAULT FALSE,
    inception_date  DATE,
    display_order   SMALLINT    NOT NULL DEFAULT 1000,
    cluster_id      SMALLINT,
    cluster_label   TEXT,
    metadata        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE  finance.assets IS
    'Référentiel des ETF, actions et actifs crypto suivis par le tracker.';
COMMENT ON COLUMN finance.assets.ticker IS
    'Libellé court utilisé dans le dashboard (XLK, ASML, SMA92…).';
COMMENT ON COLUMN finance.assets.yahoo_symbol IS
    'Symbole exact interrogé sur Yahoo Finance (ASML.AS, S92.DE…).';
COMMENT ON COLUMN finance.assets.universe IS
    'core = 15 actifs du script R ; stock = actions ciblées ; tech = ETF tech/semi additionnels.';
COMMENT ON COLUMN finance.assets.display_order IS
    'Ordre d''affichage dans les matrices ; recalculé par le clustering hiérarchique.';

-- ───────────────────────────────────────────────────────────────────────────
--  2. Prix et taux de change
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS finance.prices_daily (
    asset_id    SMALLINT    NOT NULL REFERENCES finance.assets (asset_id) ON DELETE CASCADE,
    trade_date  DATE        NOT NULL,
    open        NUMERIC(18, 6),
    high        NUMERIC(18, 6),
    low         NUMERIC(18, 6),
    close       NUMERIC(18, 6) NOT NULL CHECK (close > 0),
    adj_close   NUMERIC(18, 6) NOT NULL CHECK (adj_close > 0),
    volume      BIGINT,
    currency    CHAR(3)     NOT NULL,
    source      TEXT        NOT NULL DEFAULT 'yahoo',
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (asset_id, trade_date)
);

CREATE INDEX IF NOT EXISTS idx_prices_date
    ON finance.prices_daily (trade_date DESC);
CREATE INDEX IF NOT EXISTS idx_prices_asset_date
    ON finance.prices_daily (asset_id, trade_date DESC);

COMMENT ON TABLE finance.prices_daily IS
    'Cours quotidiens bruts et ajustés (splits/dividendes). Une ligne par actif et par séance.';
COMMENT ON COLUMN finance.prices_daily.adj_close IS
    'Clôture ajustée : base des rendements totaux et des corrélations.';

CREATE TABLE IF NOT EXISTS finance.fx_daily (
    currency    CHAR(3)     NOT NULL,
    trade_date  DATE        NOT NULL,
    eur_per_unit NUMERIC(18, 10) NOT NULL CHECK (eur_per_unit > 0),
    source      TEXT        NOT NULL DEFAULT 'yahoo',
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (currency, trade_date)
);

CREATE INDEX IF NOT EXISTS idx_fx_date
    ON finance.fx_daily (trade_date DESC);

COMMENT ON TABLE finance.fx_daily IS
    'Taux de conversion vers EUR : 1 unité de devise = eur_per_unit EUR. EUR implicite = 1.';

